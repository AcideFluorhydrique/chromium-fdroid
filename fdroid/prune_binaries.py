#!/usr/bin/env python3
"""Delete the prebuilt binaries chrome_public_apk does not need.

Usage: prune_binaries.py <chromium src dir> <prune list>

The prune list (plain text or .gz, one path per line relative to src, '#'
comments allowed) is generated by .github/scripts/scan_rules.py from the
fdroid scanner findings and the chrome_public_apk build graph: it lists the
files fdroid scanner flags that the build never reads, mostly test, fuzzing
and benchmark data. Only those files are deleted, never whole directories,
since test directories still hold BUILD.gn files that gn gen loads.

Meant to run before the scan, e.g. in a build recipe's prebuild step.
"""

import gzip
import os
import sys


def read_list(path):
    opener = gzip.open if path.endswith('.gz') else open
    with opener(path, 'rt') as f:
        for line in f:
            line = line.split('#', 1)[0].strip()
            if line:
                yield line


def main():
    src, prune_list = sys.argv[1], sys.argv[2]
    deleted = missing = 0
    freed = 0
    for rel in read_list(prune_list):
        if rel.startswith('/') or '..' in rel.split('/'):
            sys.exit(f'refusing unsafe path: {rel}')
        path = os.path.join(src, rel)
        try:
            freed += os.lstat(path).st_size
            os.remove(path)
            deleted += 1
        except FileNotFoundError:
            missing += 1
    print(f'pruned {deleted} files ({freed / 2**20:.0f} MiB); '
          f'{missing} listed files were not present')


if __name__ == '__main__':
    main()
