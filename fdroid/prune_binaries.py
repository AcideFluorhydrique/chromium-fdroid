#!/usr/bin/env python3
"""Delete the prebuilt binaries chrome_public_apk does not need.

Usage: prune_binaries.py <chromium src dir> <prune list>
       prune_binaries.py --restore <version> <chromium src dir> <prune list>

The prune list (plain text or .gz, one path per line relative to src, '#'
comments allowed) is generated by .github/scripts/scan_rules.py from the
fdroid scanner findings and the chrome_public_apk build graph: it lists the
files fdroid scanner flags that the build never reads, mostly test, fuzzing
and benchmark data. Only those files are deleted, never whole directories,
since test directories still hold BUILD.gn files that gn gen loads.

Files a .grd or .grdp includes are kept even when listed: grit reads them
through a depfile, so they are not in `ninja -t inputs` and the prune list
cannot tell they are used (components_resources.grd and the dom_distiller
models, run 44577794509). Any listed file whose name is the name of a file a
.grd/.grdp includes is kept, which may keep a few more than needed.

--restore puts back the listed files that are kept now but are missing (a
tree pruned before this rule), from chromium/src on Gitiles at <version>.

Meant to run before the scan, e.g. in a build recipe's prebuild step.
"""

import base64
import gzip
import os
import re
import sys
import time
import urllib.request

GRIT_FILE = re.compile(rb'\bfile="([^"]+)"')
GITILES = 'https://chromium.googlesource.com/chromium/src/+/refs/tags/{}/{}?format=TEXT'


def read_list(path):
    opener = gzip.open if path.endswith('.gz') else open
    with opener(path, 'rt') as f:
        for line in f:
            line = line.split('#', 1)[0].strip()
            if line:
                yield line


def grit_names(src):
    """Names of the files any .grd or .grdp under src includes."""
    names = set()
    for root, dirs, files in os.walk(src):
        dirs[:] = [d for d in dirs if d not in ('out', '.git')]
        for f in files:
            if f.endswith(('.grd', '.grdp')):
                with open(os.path.join(root, f), 'rb') as fh:
                    for m in GRIT_FILE.finditer(fh.read()):
                        names.add(os.path.basename(m.group(1).decode('utf-8', 'replace')))
    return names


def safe(rel):
    if rel.startswith('/') or '..' in rel.split('/'):
        sys.exit(f'refusing unsafe path: {rel}')
    return rel


def restore(version, src, prune_list):
    keep = grit_names(src)
    # Files fdroid/replaced-files.txt deletes on purpose stay deleted.
    here = os.path.dirname(os.path.abspath(__file__))
    replaced = set(read_list(os.path.join(here, 'replaced-files.txt')))
    restored = 0
    for rel in read_list(prune_list):
        path = os.path.join(src, safe(rel))
        if os.path.basename(rel) not in keep or os.path.lexists(path) or rel in replaced:
            continue
        url = GITILES.format(version, rel)
        for attempt in range(5):
            try:
                with urllib.request.urlopen(url, timeout=60) as r:
                    data = base64.b64decode(r.read())
                break
            except Exception as e:  # 429/5xx from Gitiles: retry
                err = e
                time.sleep(10 * (attempt + 1))
        else:
            # Not fatal: a file of another DEPS repository, or of a package
            # build provides itself (fdroid/replaced-*.txt).
            print(f'not restored {rel}: {err} (a file from another repository in DEPS?)')
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'wb') as f:
            f.write(data)
        print(f'restored {rel} ({len(data)} bytes)')
        restored += 1
    print(f'restored {restored} files')


def main():
    if sys.argv[1] == '--restore':
        return restore(*sys.argv[2:5])
    src, prune_list = sys.argv[1], sys.argv[2]
    keep = grit_names(src)
    deleted = missing = kept = 0
    freed = 0
    for rel in read_list(prune_list):
        path = os.path.join(src, safe(rel))
        if os.path.basename(rel) in keep:
            kept += 1
            continue
        try:
            freed += os.lstat(path).st_size
            os.remove(path)
            deleted += 1
        except FileNotFoundError:
            missing += 1
    print(f'pruned {deleted} files ({freed / 2**20:.0f} MiB); '
          f'{missing} listed files were not present; '
          f'{kept} kept because a .grd/.grdp includes a file of that name')


if __name__ == '__main__':
    main()
